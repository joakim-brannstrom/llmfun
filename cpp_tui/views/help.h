/// The help page (`?`, views/help.cpp): one searchable page that explains the interface
/// (design FR-27, task 42).
///
///     Help                                                        Close
///     Search the page
///     -------------------------------------------------------------------
///     Keys
///       anywhere
///       Ctrl+K        Open the command palette
///       Ctrl+B        Show or hide the session list
///       composer
///       Up            Recall the previous query
///     Commands
///     ...
///     Esc close   / search   PgUp/PgDn scroll
///
/// Sections, in the order the design names them: **Keys** (generated from the binding
/// registry), **Commands** (the palette's command table, with its descriptions), **Regions**
/// (one paragraph per region) and **Raw Log** (the developer stream). `?` opens the page and
/// `Esc` closes it - one press, the chain's first step (`views::closeTopOverlay`). `/` focuses
/// the search field; the field narrows the page by substring over the row's key **and** its
/// sentence, so `ctrl` finds the chords and `composer` finds the region.
///
/// Why the key section is generated and not written. D-KEYGATE's rule is that no binding ships
/// without a row in `plan/key_gate.md`, and the document (`doc/ui_keys.md`) is generated from the
/// same table. A hand-written key list here would be a third source, and the first to be wrong
/// (`./test_help` compares this page's key rows with the generated document in both
/// directions). The prose - the region paragraphs and the command descriptions - is authored;
/// the tables are not.
///
/// Layering (D-ADAPTER): this file is a view. It receives its state, its rectangle and the
/// metrics, reads no display size, names no v4 type and includes no `tui.h`; the frame layer
/// (`views/shell.cpp`) owns the open flag's consequences (`Esc`, the z-order, the keyboard).
#pragma once

#include <array>
#include <cstddef>
#include <string>
#include <vector>

// Forward declarations, not includes (the palette header's rule): this header travels inside
// `TuiState`, so a translation unit that reaches it must not need the `cpp_tui` include root
// just because a geometry type was mentioned.
namespace llmfun::tui::ui {
struct Metrics;
struct Rect;
} // namespace llmfun::tui::ui

namespace llmfun::tui::views {

// ---------------------------------------------------------------------------
// The page's vocabulary (the one place its strings live)
// ---------------------------------------------------------------------------

inline constexpr const char* kHelpTitle = "Help";
inline constexpr const char* kHelpSearchHint = "Search the page";
inline constexpr const char* kHelpCloseLabel = "Close";
/// The empty state: a query that matches no row says so instead of drawing a blank page (design
/// §6.9's "every surface that can be empty specifies its empty text").
inline constexpr const char* kHelpEmpty = "no matches";
/// The hint ladder, longest first: the row draws the longest one that fits *whole*, so a 40-cell
/// page keeps the two keys that matter and never a fragment of a word (the now bar's rule).
inline constexpr const char* kHelpHints[] = {
    "Esc close   / search   PgUp/PgDn scroll",
    "Esc close   / search   PgUp/PgDn",
    "Esc close   / search",
    "Esc close",
};
inline constexpr std::size_t kHelpHintCount = sizeof(kHelpHints) / sizeof(kHelpHints[0]);

// ---------------------------------------------------------------------------
// The page's model (what the sections are made of)
// ---------------------------------------------------------------------------

/// One row of the Keys section: a chord the registry binds, the action's name, the sentence the
/// registry gives it, and the group (scope) it is listed under.
///
/// Generated by `helpKeyRows()` from `model::defaultKeymap()` - the same table
/// `model::uiKeysMarkdown()` prints - so the page cannot advertise a chord the build does not
/// bind, or miss one it does.
struct HelpKeyRow {
    std::string chord;   ///< `model::chordLabel()`: "Ctrl+K", "Shift+/", "End"
    std::string action;  ///< `model::actionName()`: "ToggleRail" (the registry's own name)
    std::string summary; ///< the registry's one-line sentence for a reader
    std::string group;   ///< "anywhere" | "composer" | "overlays" | ...
};

/// The registry's binding rows, one per binding, in table order - the same rows `doc/ui_keys.md`
/// prints. Generated here, so the page cannot advertise a chord the build does not bind, or miss
/// one it does; `helpPage()` folds the repeats the registry needs (a modal surface is a keyboard
/// trap, so a chord is bound once per region it must survive in) and groups the rest.
std::vector<HelpKeyRow> helpKeyRows();

/// One entry of the page before filtering: `group` (a sub-header inside the section, "" for
/// none), the left column (a chord, a command, a region name) and the right column (the action,
/// the description, the paragraph).
///
/// `paragraph` marks prose: it is drawn as the `group`'s body and wrapped to the page's width,
/// where an ordinary entry is one line of two columns.
struct HelpEntry {
    std::string group;
    std::string left;
    std::string right;
    bool paragraph = false;
};

/// One section of the page: its title and its entries in reading order.
struct HelpSection {
    std::string name;
    std::vector<HelpEntry> entries;
};

/// The whole page, unfiltered and unwrapped - the one source of its content.
///
/// Built on demand (the sections are strings; building them is a few hundred bytes) and
/// deterministic: no clock, no frame, no ImGui context, so a test can read it headless.
std::vector<HelpSection> helpPage();

// ---------------------------------------------------------------------------
// The page's state and rendering
// ---------------------------------------------------------------------------

/// What a row of the *drawn* page is.
enum class HelpRowKind {
    Section,   ///< a section title (`Keys`)
    Group,     ///< a sub-header (`anywhere`, `rail`)
    Entry,     ///< one two-column line (`Ctrl+K` + its sentence)
    Paragraph, ///< one wrapped line of prose
};

/// One drawn row. The renderer walks these; `rebuildHelp()` is the only writer.
struct HelpRow {
    HelpRowKind kind = HelpRowKind::Entry;
    std::string left;
    std::string right;
};

/// The page's state. `open`, `query` and the scroll position survive across frames; `rows` is
/// derived (rebuilt when the query or the width moved, never per frame).
struct HelpState {
    bool open = false;
    std::array<char, 128> query = {};

    /// The drawn page: sections, groups, entries and the wrapped prose lines.
    std::vector<HelpRow> rows;
    /// The query and the inner width `rows` was built for - the two inputs of the rebuild.
    std::string builtQuery;
    int builtWidth = -1;
    /// Entries that survived the filter (not counting section and group headers).
    int matches = 0;
    /// The left column's width in cells, clamped to a third of the page.
    int leftColumn = 0;

    /// First drawn row, the rows the last frame could show, and how many it drew.
    int firstVisible = 0;
    int viewportRows = 0;
    int drawnRows = 0;

    /// The `/` request, armed until the field really owns the keyboard (ImGui applies
    /// `SetKeyboardFocusHere()` on the item's next Begin, which can be a frame later), and the
    /// observation that the field is active this frame - the frame wiring and `./test_help` read
    /// it, and the keys use it to tell a field-typing frame from a page-typing one.
    bool searchFocus = false;
    bool searchFocused = false;
    /// The id suffix, so a reopened page re-reads the field's buffer instead of ImGui's stale
    /// edit state (the settings sheet's rule).
    unsigned searchSeq = 0;
    /// The title row's `Close` control: the pointer's way out (task 34's shape).
    bool closeRequested = false;
};

/// Open the page: no query, no scroll, nothing to carry over from the last time it was up. The
/// search field does *not* take the keyboard - `/` is the key that does, and a page that opened
/// with the keyboard in its field would type the first letter of the next chord into a search.
void openHelp(HelpState& state);

/// Close the page and drop its query. Drawing nothing next frame is the caller's job (`open` is
/// false).
void closeHelp(HelpState& state);

/// Rebuild `rows` from `helpPage()` for `query` and `innerCells`: filter by substring, emit the
/// section and group headers of what survived, and wrap the prose to the width.
///
/// The page's content does not change with the frame, so this runs on a query change and on a
/// width change only (`builtQuery`/`builtWidth` are the key). `innerCells` is a cell budget in
/// both profiles - the pixel profile's is `innerW / gu`, an approximation that keeps the wrap of
/// a proportional font close to the box without a per-word measurement pass.
void rebuildHelp(HelpState& state, int innerCells);

/// Draw and drive the page inside `region` - the box `ui::computeShell()` answered for it (a view
/// positions nothing). `ownsKeyboard` is the frame's answer for "nothing above this surface holds
/// the keyboard": the page then reads `/` and the scroll keys.
void renderHelp(HelpState& state, const ui::Rect& region, const ui::Metrics& m, bool ownsKeyboard);

} // namespace llmfun::tui::views
