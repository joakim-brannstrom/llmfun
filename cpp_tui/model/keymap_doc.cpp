/// Where a binding is live, in the words a user needs: `everywhere` is the design's *Anywhere*,
/// and a named region is the surface that owns the keyboard.
const char* scopeLabel(const Scope& scope) {
    if (scope.isAnywhere())
        return "everywhere";
    switch (scope.region()) {
    case Focus::Composer:
        return "composer";
    case Focus::Rail:
        return "rail";
    case Focus::Thread:
        return "thread";
    case Focus::Overlay:
        return "palette/overlay";
    case Focus::RawLog:
        return "Raw Log";
    case Focus::Settings:
        return "settings sheet";
    case Focus::Help:
        return "help page";
    case Focus::None:
    case Focus::Count:
        break;
    }
    return "nothing focused";
}

/// How an action is reached besides the table (`ActionReach`), in one short phrase.
const char* reachLabel(ActionReach reach) {
    switch (reach) {
    case ActionReach::Palette:
        return "palette row";
    case ActionReach::Chord:
        return "chord only";
    case ActionReach::EscapeChain:
        return "Esc chain";
    }
    return "";
}

