std::string uiKeysMarkdown() {
    std::string text;
    text += "# llmfun keys\n";
    text += "\n";
    text += "Generated by `tools/gen_ui_keys.sh` from three sources, never edited by hand:\n";
    text += "\n";
    text +=
        "- the binding table (`cpp_tui/model/keymap.cpp`: every row, its region and its other\n";
    text += "  entry point);\n";
    text += "- the `Esc` chain, whose steps are `model::resolveEscape()`'s code;\n";
    text += "- the rail's row keys (`cpp_tui/model/rail_keys.h`, the table `views/rail.cpp` reads "
            "its\n";
    text += "  characters from).\n";
    text += "\n";
    text +=
        "`./test_ui_keys` compares this file with those sources, so a binding, a chain step or a\n";
    text +=
        "row key that changes without regenerating it fails the build. The prose paragraphs are\n";
    text +=
        "reviewed by hand; the tables are generated - except the Composer keys rows that repeat\n";
    text += "`Up`/`Down` and their `Ctrl` aliases, which are prose and can drift from the registry "
            "row\n";
    text += "above them.\n";
    text += "\n";
    text +=
        "**What this document covers.** The registry rows, the `Esc` chain and the rail's row\n";
    text +=
        "keys. It does not list the character keys a surface reads for itself - the Raw Log's\n";
    text +=
        "`f`/`p`/`/`/`y`, the inspector's `[`/`]` and its hovered `m`, the settings sheet's list\n";
    text +=
        "keys, the palette's, the help page's `?`, and the frame's `x` (it answers a persistent\n";
    text +=
        "feedback flash: a warning or an error stays until a key does) - because those literals\n";
    text +=
        "live at their call sites rather than in one table (the rail's are the ones lifted into\n";
    text += "`rail_keys.h`). The terminal delivers no key event for a printable character, so\n";
    text += "`Shift+/` is a row for the pixel profile and a typed character for the grid.\n";
    text += "\n";
    text += "One binding per row; `where` is the region that owns the keyboard. A chord with no\n";
    text +=
        "modifier never fires while a text field has the keyboard, and an overlay is a keyboard\n";
    text += "trap: while it is open only its own rows (and the ones repeated for it) fire.\n";
    text += "\n";
    text += "| key | action | where | also reachable |\n";
    text += "| --- | --- | --- | --- |\n";
    for (const Binding& binding : defaultKeymap()) {
        const ActionInfo* info = actionInfo(binding.action);
        text += "| ";
        text += chordLabel(binding.chord);
        text += " | ";
        text += info != nullptr ? info->name : actionName(binding.action);
        text += " | ";
        text += scopeLabel(binding.when);
        text += " | ";
        text += info != nullptr ? reachLabel(info->reach) : "";
        text += " |\n";
    }

    // `Esc` has a resolver, not a row (D-ESC): its five steps are one press each, in this order.
    text += "\n";
    text += "## Esc\n";
    text += "\n";
    text +=
        "`Esc` is not a registry row: its action depends on the run and the input, and the order\n";
    text +=
        "lives in one function (`model::resolveEscape`). One step per press. The steps below are\n";
    text += "derived from that function - each state is asked of the resolver, so a reordering "
            "shows up\n";
    text += "here - and the sentence after each name says what the step means:\n";
    text += "\n";
    const EscapeContext stepStates[] = {
        {true, true, true},        // an overlay is up
        {false, true, true, true}, // focus mode is on (and a run and a draft are too)
        {false, true, true},       // a run is active
        {false, false, true},      // a draft is in the field
        {false, false, false},
    };
    const char* stepMeaning[] = {
        "close the topmost overlay (help page, palette, settings sheet, Raw Log, inspector panel, "
        "rail panel)",
        "leave focus mode (the side panels and the bar come back; the draft and the run are "
        "untouched)",
        "cancel the running agent (the same request `/stop` makes; partial output is kept)",
        "clear the composer's draft",
        "release the keyboard",
    };
    for (int i = 0; i < 5; ++i) {
        text += std::to_string(i + 1);
        text += ". `";
        text += actionName(resolveEscape(stepStates[i]));
        text += "` - ";
        text += stepMeaning[i];
        text += ";\n";
    }
    text += "\n";
    text +=
        "A view that owns a press of its own (the rail's rename box, its search field, its row\n";
    text +=
        "menu) spends it before the chain sees it, and the frame's chain stands down for that\n";
    text += "press.\n";

    // The rail's row keys are *characters*, read by the view (plan/key_gate.md F2), so they are
    // not `Action` rows and a table generated from the registry alone would omit them.
    text += "\n";
    text += "## Rail row keys\n";
    text += "\n";
    text +=
        "The rail reads these as characters, not as registry rows: they act on the row the user\n";
    text += "aimed at (the pointer's row, or the keyboard-focused one), and a collapsed rail\'s "
            "strip\n";
    text += "carries none of them.\n";
    text += "\n";
    text += "| key | action |\n";
    text += "| --- | --- |\n";
    text += "| `";
    text += kRailSearchKey;
    text += "` | focus the search field (from anywhere except the composer) |\n";
    for (std::size_t i = 0; i < kRailRowKeyCount; ++i) {
        text += "| `";
        text += kRailRowKeys[i].key;
        text += "` | ";
        text += kRailRowKeys[i].action;
        text += " |\n";
    }
    text += "| `Enter` | in the search field: select the best match |\n";

    // The composer's own keys: the field's, resolved through the same registry.
    text += "\n";
    text += "## Composer keys\n";
    text += "\n";
    text += "| key | action |\n";
    text += "| --- | --- |\n";
    text += "| `Enter` | newline in the draft - the terminal delivers `Shift+Enter` and "
            "`Ctrl+Enter` as the same byte (plan/key_gate.md §3), so `Enter` cannot send; the "
            "composer's `Send` does |\n";
    text += "| `Up` / `Ctrl+Up` | recall the previous query |\n";
    text += "| `Down` / `Ctrl+Down` | recall the next query |\n";
    text += "| `/` on an empty line | open the palette's command entry |\n";
    // The delivery caveat: a row is evidence, not a wish (D-KEYGATE). The measurements live in
    // plan/key_gate.md; the two consequences a user meets are named here.
    text += "\n";
    text += "## Delivery\n";
    text += "\n";
    text +=
        "A row exists only where the chord is actually delivered. Three consequences are worth\n";
    text += "knowing before a key looks broken:\n";
    text += "\n";
    text +=
        "- the terminal does not deliver `Ctrl+I`, `Ctrl+5` or `Ctrl+6` (byte 9 is `Tab`, and\n";
    text +=
        "  `0x1D`/`0x1E` are unmapped). The inspector is reached there through the palette rows,\n";
    text += "  the top bar's `Settings` entry and the panel's own `[`/`]` tab keys;\n";
    text +=
        "- `Ctrl+Shift+L` arrives as `Ctrl+L` in the terminal (the Shift is lost), so the grid's\n";
    text += "  paths to the Raw Log are `/rawlog`, the palette's Developer row and `--debug-ui`;\n";
    text += "- `Shift+/` is `?`, and the terminal delivers it as that typed character rather than "
            "as a\n";
    text +=
        "  key, so the help page opens there from the character (`views/shell.cpp` reads it) and\n";
    text += "  from the chord in the pixel profile.\n";
    text += "\n";
    text += "`Ctrl+C` is not bound at all: the terminal turns it into `SIGINT` before the UI reads "
            "it,\n";
    text += "and in the GUI it is the text field's copy chord.\n";

    return text;
}

